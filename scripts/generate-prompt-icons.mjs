#!/usr/bin/env node
// Generates packages/core/src/prompt/icons.ts: the AI services' logos the prompt plugins ship, as SVG markup filled with `currentColor`, so the plugins need no icon packages at runtime. The icons come from Lobe Icons (MIT, © LobeHub, https://github.com/lobehub/lobe-icons), at the version below; the logos themselves remain their owners' trademarks. Rerun after moving the version, then format the output with `vp fmt`:
//
//   node scripts/generate-prompt-icons.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "packages/core/src/prompt/icons.ts");

const VERSION = "1.102.0";

// Each built-in service's id, and the Lobe icon it shows.
const icons = {
  chatgpt: `openai`,
  claude: `claude`,
  copilot: `copilot`,
  cursor: `cursor`,
  gemini: `gemini`,
  "github-copilot": `githubcopilot`,
  grok: `grok`,
  mistral: `mistral`,
  perplexity: `perplexity`
};

const fetchIcon = async (name) => {
  const url = `https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@${VERSION}/icons/${name}.svg`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
};

// The markup the plugins need: the viewBox and the paths, without the size, inline style and title Lobe adds for its React components. The service's name is on the button, so the icon is decorative.
const clean = (name, svg) => {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!viewBox || typeof body !== `string`) {
    throw new Error(`The icon "${name}" isn't an SVG`);
  }
  const content = body.replace(/<title>[\s\S]*?<\/title>/, ``).trim();
  return `<svg viewBox="${viewBox}" fill="currentColor" fill-rule="evenodd">${content}</svg>`;
};

const entries = await Promise.all(
  Object.entries(icons).map(async ([id, name]) => [
    id,
    clean(name, await fetchIcon(name))
  ])
);

writeFileSync(
  output,
  `// Generated by scripts/generate-prompt-icons.mjs from Lobe Icons (MIT, © LobeHub, https://github.com/lobehub/lobe-icons) ${VERSION}. The logos remain their owners' trademarks. Don't edit it by hand: rerun the script.

/** Each built-in service's logo, as SVG markup filled with \`currentColor\`. */
export const PROMPT_SERVICE_ICONS: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};
`
);

console.log(`${entries.length} icons`);
